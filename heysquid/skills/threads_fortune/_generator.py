# ── 연운 보정 키워드 (병오년 = 화 에너지) ────────────────────

def _get_year_energy(d: date) -> dict:
    """연주 계산 + 올해의 에너지 키워드."""
    y = d.year
    stem_idx = (y - 4) % 10
    branch_idx = (y - 4) % 12
    stem = HEAVENLY_STEMS[stem_idx]
    element = STEM_ELEMENT[stem]
    return {
        "stem": stem,
        "branch": EARTHLY_BRANCHES[branch_idx],
        "element": element,
    }


# ── 결정론적 해시 기반 인덱스 선택 ───────────────────────────

def _pick_index(seed: str, pool_size: int) -> int:
    """seed 문자열에서 결정론적으로 인덱스 선택."""
    h = int(hashlib.md5(seed.encode()).hexdigest(), 16)
    return h % pool_size


# ── 오행 상생상극 기반 추가 뉘앙스 ───────────────────────────

def _element_relation(day_element: str, branch_element: str) -> str:
    """일간 오행과 띠 오행의 관계."""
    if _SANGSAENG.get(day_element) == branch_element:
        return "생(生)"  # 일간이 띠를 생함 → 주는 에너지
    if _SANGSAENG.get(branch_element) == day_element:
        return "받음"  # 띠가 일간을 생함 → 받는 에너지
    if _SANGGEUK.get(day_element) == branch_element:
        return "극(克)"  # 일간이 띠를 극함 → 통제
    if _SANGGEUK.get(branch_element) == day_element:
        return "피극"  # 띠가 일간을 극함 → 도전
    if day_element == branch_element:
        return "비화"  # 같은 오행 → 동질
    return "중립"


# ── 메인 생성 함수 ──────────────────────────────────────────

def _generate_advice(
    zodiac_branch: str,
    relations: list[str],
    day_element: str,
    d: date,
) -> str:
    """한 띠에 대한 10자 이내 조언 생성."""
    branch_elem = BRANCH_ELEMENT[zodiac_branch]
    seed_base = f"{d.isoformat()}:{zodiac_branch}"

    if relations[0] != "없음":
        # 관계가 있으면 해당 관계 풀에서 선택
        rel = relations[0]
        key = (rel, day_element)
        pool = _ADVICE_POOL.get(key, ["오늘도 힘내"])
        idx = _pick_index(seed_base + rel, len(pool))
        return pool[idx]
    else:
        # 관계 없음 → 띠 고유 기질 기반 풀에서 선택
        key = (zodiac_branch, day_element)
        pool = _NEUTRAL_ADVICE.get(key, ["내 페이스대로 가"])
        idx = _pick_index(seed_base + "neutral", len(pool))
        return pool[idx]


def _format_year(y: int) -> str:
    return f"{y:02d}"


def generate_daily_fortune(d: date | datetime | None = None) -> str:
    """dkbsqd 포맷 띠별 운세 생성 (500자 이내)."""
    if d is None:
        d = date.today()
    if isinstance(d, datetime):
        d = d.date()

    pillar = get_day_pillar(d)
    element = pillar["element"]
    zodiac_list = analyze_zodiac_relations(pillar["ji"])

    weekday = _WEEKDAY_KR[d.weekday()]
    header = f"{d.month}/{d.day} {weekday} 띠별 운세 🔮"

    lines = [header]
    for z in zodiac_list:
        y1 = _format_year(z["years"][0])
        y2 = _format_year(z["years"][1])

        advice1 = _generate_advice(z["branch"], z["relations"], element, d)
        # 두 번째 연도는 다른 시드로
        seed2 = f"{d.isoformat()}:{z['branch']}:y2"
        if z["relations"][0] != "없음" and len(z["relations"]) > 1:
            advice2 = _generate_advice(z["branch"], z["relations"][1:], element, d)
        else:
            # 같은 관계지만 다른 조언 선택
            branch_elem = BRANCH_ELEMENT[z["branch"]]
            rel = z["relations"][0]
            if rel != "없음":
                key = (rel, element)
                pool = _ADVICE_POOL.get(key, ["오늘도 힘내"])
                idx = _pick_index(seed2, len(pool))
                advice2 = pool[idx]
            else:
                key = (z["branch"], element)
                pool = _NEUTRAL_ADVICE.get(key, ["내 페이스대로 가"])
                idx = _pick_index(seed2, len(pool))
                advice2 = pool[idx]

        # 중복 방지
        if advice1 == advice2:
            advice2 = BRANCH_TRAITS[z["branch"]]["키워드"][
                _pick_index(seed2 + "alt", len(BRANCH_TRAITS[z["branch"]]["키워드"]))
            ] + " 발휘해"

        line = f"{z['emoji']}{y1}년생: {advice1}/{y2}년생: {advice2}"
        lines.append(line)

    return "\n".join(lines)


def generate_fortune_with_context(d: date | datetime | None = None) -> dict:
    """AI 다듬기용 전체 데이터 반환."""
    if d is None:
        d = date.today()
    if isinstance(d, datetime):
        d = d.date()

    pillar = get_day_pillar(d)
    analysis = analyze_zodiac_relations(pillar["ji"])
    year_energy = _get_year_energy(d)
    text = generate_daily_fortune(d)

    # 각 띠에 오행 관계 정보 추가
    for a in analysis:
        branch_elem = BRANCH_ELEMENT[a["branch"]]
        a["branch_element"] = branch_elem
        a["element_relation"] = _element_relation(pillar["element"], branch_elem)
        a["traits"] = BRANCH_TRAITS[a["branch"]]

    return {
        "date": d.isoformat(),
        "pillar": pillar,
        "year_energy": year_energy,
        "zodiac_analysis": analysis,
        "formatted_text": text,
        "first_comment": "👇가장 정확한 오늘의 운세는 여기 DKBSQD.com 🔮",
    }
